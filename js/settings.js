/* ========================================
   IDEA AGENT — Settings Module
   Theme, API key, preferences
   ======================================== */

var Settings = {
  render() {
    const s = Store.getSettings();
    const u = Store.getStorageUsage();
    const S = (t, c, d=0) => `<div class="settings-section animate-slide-up" style="animation-delay:${d}s"><h2>${t}</h2>${c}</div>`;
    const R = (l, d, r, x='') => `<div class="settings-row" ${x}><div><div class="settings-row-label">${l}</div><div class="settings-row-desc">${d}</div></div>${r}</div>`;

    const secUi = S('🎨 Giao diện', R('Dark Mode', 'Chế độ tối', `<label class="toggle-switch"><input type="checkbox" id="settings-theme" ${s.theme === 'dark' ? 'checked' : ''} onchange="Settings.toggleTheme(this.checked)"><span class="toggle-slider"></span></label>`));

    const googleBtn = GoogleAuth.isSignedIn ? '<button class="btn btn-secondary btn-sm" onclick="GoogleAuth.signOut()">Đăng xuất</button>' : '<button class="btn btn-secondary btn-sm" onclick="GoogleAuth.signIn()">Đăng nhập</button>';
    const googleLabel = GoogleAuth.isSignedIn && GoogleAuth.userInfo ? '🟢 ' + Utils.escapeHtml(GoogleAuth.userInfo.email) : '👤 Đăng nhập Google (tên & avatar)';

    const secAi = S('🤖 DeepSeek AI', `
      <div class="settings-row"><div style="flex:1"><div class="settings-row-label">🔑 API Key</div><div class="settings-row-desc">Lấy key từ <a href="https://platform.deepseek.com/api_keys" target="_blank" rel="noopener" style="color:var(--primary)">DeepSeek Platform</a></div></div></div>
      <div style="display:flex;gap:var(--space-sm);margin-top:var(--space-sm)"><input type="password" class="form-input" id="settings-api-key" value="${s.geminiApiKey || ''}" placeholder="sk-..." aria-label="DeepSeek API Key"><button class="btn btn-secondary" aria-label="Hiện/ẩn API Key" onclick="Settings.toggleApiKeyVisibility()">👁️</button><button class="btn btn-primary" onclick="Settings.saveApiKey()">Lưu</button></div>
      <div style="margin-top:var(--space-xs);font-size:0.75rem;color:var(--text-muted)">🔒 Lưu cục bộ trên thiết bị (localStorage).</div>
      <div class="settings-row" style="margin-top:var(--space-md);padding:var(--space-sm) var(--space-md);background:var(--bg-tertiary);border-radius:var(--radius-md)"><div style="flex:1"><div class="settings-row-label" style="font-size:0.85rem">${googleLabel}</div></div><div>${googleBtn}</div></div>
      ${R('Model', 'Model AI tạo bản thảo', `<select class="form-select" id="settings-model" style="width:200px" onchange="Settings.saveModel(this.value)"><option value="deepseek-chat" ${(s.geminiModel === 'deepseek-chat' || !s.geminiModel) ? 'selected' : ''}>DeepSeek V3</option><option value="deepseek-reasoner" ${s.geminiModel === 'deepseek-reasoner' ? 'selected' : ''}>DeepSeek R1</option></select>`, 'style="margin-top:var(--space-sm)"')}
      ${R('Auto Draft', 'Tự tạo bản thảo khi lưu ý tưởng', `<label class="toggle-switch"><input type="checkbox" id="settings-auto-draft" ${s.autoGenerateDraft ? 'checked' : ''} onchange="Settings.toggleAutoDraft(this.checked)"><span class="toggle-slider"></span></label>`)}
      <div style="margin-top:var(--space-md)"><button class="btn btn-secondary btn-sm" onclick="Settings.testConnection()">🧪 Test kết nối AI</button></div>
    `, 0.05);

    const secDef = S('📝 Mặc định', R('Danh mục mặc định', 'Chọn sẵn khi tạo ý tưởng', `<select class="form-select" id="settings-default-cat" style="width:180px" onchange="Settings.saveDefaultCategory(this.value)">${Utils.renderOptions(Utils.categories, s.defaultCategory)}</select>`), 0.1);

    const storageGauge = `<div style="min-width:140px;display:flex;align-items:center;gap:var(--space-sm)"><div style="flex:1;height:8px;background:var(--bg-tertiary);border-radius:4px;overflow:hidden"><div id="storage-usage-bar" style="width:${Math.max(2, u.pct)}%;height:100%;background:${u.pct > 80 ? 'var(--danger)' : 'var(--primary)'};border-radius:4px;transition:width 0.3s ease"></div></div><span style="font-size:0.75rem;color:var(--text-muted);font-weight:600">${u.pct}%</span></div>`;

    const secData = S('💾 Dữ liệu', `
      ${R('Dung lượng bộ nhớ', `<span id="storage-usage-text">${u.kb} KB / ~5.120 KB (${u.pct}%)</span>`, storageGauge)}
      ${R('Export tất cả', 'Tải file JSON sao lưu ý tưởng', `<button class="btn btn-secondary btn-sm" onclick="Settings.exportAll()">${Utils.icon('export', 16)} Export JSON</button>`)}
      ${R('Import dữ liệu', 'Khôi phục từ file JSON đã tải', `<div><input type="file" id="import-file" accept=".json" style="display:none" onchange="Settings.importFile(this.files[0]); this.value='';"><button class="btn btn-secondary btn-sm" onclick="document.getElementById('import-file').click()">📥 Import JSON</button></div>`)}
      ${R('<span style="color:var(--danger)">Xóa toàn bộ</span>', 'Không thể hoàn tác sau khi xóa!', `<button class="btn btn-danger btn-sm" onclick="Settings.clearAll()">${Utils.icon('delete', 16)} Xóa tất cả</button>`)}
    `, 0.15);

    const secInfo = S('ℹ️ Thông tin', '<div style="font-size:0.85rem;color:var(--text-secondary);line-height:1.7"><strong>Idea Agent</strong> v2.0<br>Hệ thống ghi nhận & phát triển ý tưởng · DeepSeek AI<br><span style="color:var(--text-muted)">Dữ liệu lưu trữ tại localStorage trên thiết bị</span></div>', 0.2);

    return `<div class="page-header"><h1>⚙️ Cài đặt</h1></div>${secUi}${secAi}${secDef}${secData}${secInfo}`;
  },

  // ========================
  // THEME
  // ========================

  toggleTheme(isDark) {
    const theme = isDark ? 'dark' : 'light';
    document.documentElement.setAttribute('data-theme', theme);
    Store.updateSettings({ theme });
    App.updateThemeIcon();
  },

  // ========================
  // AI API
  // ========================

  saveApiKey() {
    const input = document.getElementById('settings-api-key');
    if (!input) return;
    const key = input.value.trim();
    Store.updateSettings({ geminiApiKey: key });
    Utils.showToast(key ? '✅ API Key đã lưu' : '⚠️ API Key đã xóa', key ? 'success' : 'info');
    App.updateAIStatusBadge();
  },

  toggleApiKeyVisibility() {
    const input = document.getElementById('settings-api-key');
    if (input) {
      input.type = input.type === 'password' ? 'text' : 'password';
    }
  },

  saveModel(model) {
    Store.updateSettings({ geminiModel: model });
    Utils.showToast(`Model: ${model}`, 'info');
  },

  async testConnection() {
    const settings = Store.getSettings();

    if (!settings.geminiApiKey) {
      Utils.showToast('Vui lòng nhập API Key trước', 'error');
      return;
    }

    Utils.showToast('🧪 Đang kiểm tra kết nối AI...', 'info');

    try {
      const result = await AI.call('Trả lời ngắn gọn bằng tiếng Việt: Xin chào, bạn là AI gì?', settings);
      Utils.showToast('✅ Kết nối thành công! ' + result.substring(0, 80), 'success');
    } catch (err) {
      Utils.showToast('❌ Lỗi: ' + err.message, 'error');
    }
  },

  toggleAutoDraft(enabled) {
    Store.updateSettings({ autoGenerateDraft: enabled });
    Utils.showToast(enabled ? '✅ Auto Draft bật' : '⚠️ Auto Draft tắt', enabled ? 'success' : 'info');
  },

  // ========================
  // DEFAULT CATEGORY
  // ========================

  saveDefaultCategory(cat) {
    Store.updateSettings({ defaultCategory: cat });
    Utils.showToast(`Danh mục mặc định: ${Utils.getCategoryLabel(cat)}`, 'info');
  },

  // ========================
  // DATA MANAGEMENT
  // ========================

  exportAll() {
    const data = Store.exportData();
    const date = new Date().toISOString().split('T')[0];
    Utils.downloadFile(data, `idea-agent-backup-${date}.json`, 'application/json');
    Utils.showToast('📥 Đã export dữ liệu', 'success');
  },

  importFile(file) {
    if (!file) return;

    const reader = new FileReader();
    reader.onload = (e) => {
      const content = e.target.result;
      let parsed;
      try {
        parsed = JSON.parse(content);
      } catch (err) {
        Utils.showToast('❌ File JSON không hợp lệ hoặc bị hỏng', 'error');
        return;
      }

      if (!Store.validateData(parsed)) {
        Utils.showToast('❌ File không đúng cấu trúc (thiếu danh sách ideas hợp lệ)', 'error');
        return;
      }

      // Auto-trigger backup export before overwrite or merge
      Settings.exportAll();
      Utils.showToast('💾 Đã tự động xuất bản sao lưu trước khi nhập', 'info');

      // Save pending content in memory
      Settings._pendingImportContent = content;

      // Prompt modal for Merge vs Replace
      const modalContent = `<p style="margin-bottom:var(--space-md)">Tệp chứa <strong>${parsed.ideas.length}</strong> ý tưởng (đã tự động xuất bản sao lưu dự phòng).</p><div style="display:flex;flex-direction:column;gap:var(--space-sm)"><button class="btn btn-primary" id="btn-import-merge" onclick="Settings.executeImport('merge')">🔄 Gộp dữ liệu (Bỏ qua ID trùng)</button><button class="btn btn-secondary" id="btn-import-replace" onclick="Settings.executeImport('replace')" style="border-color:var(--danger);color:var(--danger)">⚠️ Thay thế toàn bộ</button></div>`;
      App.openModal('📥 Nhập dữ liệu sao lưu', modalContent);
    };
    reader.readAsText(file);
  },

  executeImport(mode) {
    App.closeModal();
    const content = this._pendingImportContent;
    this._pendingImportContent = null;
    if (!content) return;

    const success = Store.importData(content, mode);
    if (success) {
      Utils.showToast(`✅ Đã nhập thành công (${mode === 'merge' ? 'Gộp' : 'Thay thế'})! Tải lại trang...`, 'success');
      setTimeout(() => location.reload(), 1200);
    } else {
      Utils.showToast('❌ Lỗi khi lưu dữ liệu (Bộ nhớ đầy?)', 'error');
    }
  },

  clearAll() {
    if (confirm('⚠️ XÓA TOÀN BỘ dữ liệu? Hãy Export backup trước.') && confirm('Xác nhận lần cuối: XÓA TẤT CẢ?')) {
      Store.clearAll();
      Utils.showToast('🗑️ Đã xóa toàn bộ dữ liệu', 'info');
      setTimeout(() => location.reload(), 1000);
    }
  },
};
